#!/usr/bin/env python3
# T8-o: rebuild vault-drip.mjs with era iteration + chain judging (fixed),
# node --check, commit, dispatch dry.
import base64, hashlib, json, os, subprocess, sys, time

T8 = "/home/z/my-project/tmp/t8"
P = T8 + "/vault-drip.mjs"
L = []
a = L.append

a('#!/usr/bin/env node')
a('// vault-drip.mjs - R314b (2026-10-11): chain-judged posting WIF from the git vault.')
a('// Law: the vault IS the credential delivery; blurt was never re-keyed to GEN-2')
a('// (R267: GEN-1 fits 4/4 live blurt authorities), so the drip tries BOTH eras')
a('// (GEN-2 then GEN-1), sha-pins each archive, chain-judges every candidate')
a('// generation against the LIVE blurt posting authority (keyless saboin RPC),')
a('// and emits ONLY the fitting WIF to stdout. Wipe on every path. Fail-closed.')
a('import { execFileSync } from "node:child_process";')
a('import * as crypto from "node:crypto";')
a('import * as fs from "node:fs";')
a('import * as path from "node:path";')
a('')
a('const ACCOUNT = String(process.argv[2] ?? "headcorner").trim();')
a('const ENGINE = String(process.argv[3] ?? "/tmp/engine").trim();')
a('const TMP = "/tmp/vdrip";')
a('const RPC = "https://blurt-rpc.saboin.com";')
a('const fail = (v, r) => { try { fs.rmSync(TMP, { recursive: true, force: true }); } catch { /* best effort */ } console.error(JSON.stringify({ verdict: v, reason: String(r).slice(0, 200) })); process.exit(1); };')
a('')
a('const sha256hex = (b) => crypto.createHash("sha256").update(b).digest("hex");')
a('const B58 = "123456789ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz";')
a('function b58checkEncode(bytes) {')
a('  const h = crypto.createHash("sha256").update(crypto.createHash("sha256").update(bytes).digest()).digest().subarray(0, 4);')
a('  const all = Buffer.concat([bytes, h]);')
a('  let n = BigInt("0x" + all.toString("hex")), out = "";')
a('  while (n > 0n) { out = B58[Number(n % 58n)] + out; n /= 58n; }')
a('  for (const b of all) { if (b === 0) out = "1" + out; else break; }')
a('  return out;')
a('}')
a('function wifPriv(w) {')
a('  let n2 = 0n;')
a('  for (const ch of w) { const i = B58.indexOf(ch); if (i < 0) throw new Error("b58"); n2 = n2 * 58n + BigInt(i); }')
a('  let hx = n2.toString(16).padStart(2, "0");')
a('  if (hx.length % 2) hx = "0" + hx;')
a('  const raw = Buffer.from(hx, "hex");')
a('  const body = raw.subarray(0, raw.length - 4);')
a('  const h = crypto.createHash("sha256").update(crypto.createHash("sha256").update(body).digest()).digest().subarray(0, 4);')
a('  if (!h.equals(raw.subarray(raw.length - 4))) throw new Error("wif-checksum");')
a('  if (body[0] !== 0x80) throw new Error("wif-prefix");')
a('  return body.subarray(1);')
a('}')
a('')
a('// eras: GEN-2 (recovery meta) then GEN-1 (its era meta) - same flat shape each.')
a('const ERAS = [')
a('  { name: "GEN-2", meta: ["agent/recovery-meta.json", "agent/vault/recovery-meta.json"] },')
a('  { name: "GEN-1", meta: ["agent/vault/GEN-1-ERA-META.json"] },')
a('];')
a('function loadEra(era) {')
a('  for (const p of era.meta) {')
a('    try { return { ...JSON.parse(fs.readFileSync(path.join(ENGINE, p), "utf8")), __name: era.name }; } catch { /* next path */ }')
a('  }')
a('  return null;')
a('}')
a('function candidatesFrom(era) { // decrypt (sha-pinned) -> candidate posting wifs; wipe after')
a('  fs.rmSync(TMP, { recursive: true, force: true });')
a('  fs.mkdirSync(TMP, { recursive: true, mode: 0o700 });')
a('  const enc = fs.readFileSync(path.join(ENGINE, era.keysZipFile));')
a('  const outerPin = String(era.keysZipSha256 ?? "");')
a('  if (outerPin && sha256hex(enc) !== outerPin) throw new Error(era.__name + "-outer-sha-mismatch");')
a('  fs.writeFileSync(path.join(TMP, "k.enc"), enc, { mode: 0o600 });')
a('  execFileSync("openssl", ["enc", "-d", "-aes-256-cbc", "-pbkdf2", "-iter", "300000",')
a('    "-in", path.join(TMP, "k.enc"), "-out", path.join(TMP, "inner.zip"),')
a('    "-pass", "pass:" + era.keysZipPass], { stdio: ["ignore", "ignore", "pipe"] });')
a('  const innerPin = String(era.keysZipInnerSha256 ?? "");')
a('  const inner = fs.readFileSync(path.join(TMP, "inner.zip"));')
a('  if (innerPin && sha256hex(inner) !== innerPin) throw new Error(era.__name + "-inner-sha-mismatch");')
a('  execFileSync("unzip", ["-o", "-q", path.join(TMP, "inner.zip"), "agent/keys/vault.json", "-d", TMP],')
a('    { stdio: ["ignore", "ignore", "pipe"] });')
a('  const vault = JSON.parse(fs.readFileSync(path.join(TMP, "agent", "keys", "vault.json"), "utf8"));')
a('  fs.rmSync(TMP, { recursive: true, force: true }); // wipe BEFORE any judging')
a('  const acc = (vault.accounts ?? []).find((x) => x.username === ACCOUNT || x.name === ACCOUNT || x.account === ACCOUNT);')
a('  if (!acc) throw new Error(era.__name + "-account-absent");')
a('  const cands = [...(acc.gens ?? []).map((g) => ({ gen: String(g?.gen ?? era.__name + "?"), wif: String(g?.wif ?? "").trim() })),')
a('    { gen: era.__name + "-flat", wif: String(acc?.keys?.steem?.posting?.wif ?? acc?.keys?.posting?.wif ?? "").trim() }]')
a('    .filter((c) => c.wif.length >= 51);')
a('  if (!cands.length) throw new Error(era.__name + "-no-posting-wif");')
a('  return cands;')
a('}')
a('')
a('async function chainJudge(priv) { // noble takes the decoded key bytes directly')
a('  const pub = Buffer.from(secp.getPublicKey(priv, true));')
a('  const blt = "BLT" + b58checkEncode(pub);')
a('  const r = await fetch(RPC, {')
a('    method: "POST", headers: { "content-type": "application/json" },')
a('    body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "condenser_api.get_accounts", params: [[ACCOUNT]] }),')
a('    signal: AbortSignal.timeout(12000),')
a('  });')
a('  const j = await r.json();')
a('  if (j.error) throw new Error(String(j.error?.message ?? "rpc").slice(0, 80));')
a('  const live = j.result?.[0]?.posting?.key_auths?.[0]?.[0] ?? "";')
a('  return { blt, live, match: blt === live };')
a('}')
a('')
a('if (!fs.existsSync(path.join(ENGINE, "agent"))) fail("ENGINE-TREE-ABSENT", ENGINE);')
a('const secp = await import("@noble/secp256k1");')
a('const tried = [];')
a('let chosen = null;')
a('for (const eraDef of ERAS) {')
a('  const era = loadEra(eraDef);')
a('  if (!era || !era.keysZipPass || !era.keysZipFile) { tried.push({ era: eraDef.name, skipped: "meta-absent" }); continue; }')
a('  let cands;')
a('  try { cands = candidatesFrom(era); } catch (e) { tried.push({ era: eraDef.name, err: String(e?.message ?? e).slice(0, 80) }); continue; }')
a('  for (const c of cands) {')
a('    try {')
a('      const priv = wifPriv(c.wif);')
a('      const j = await chainJudge(priv);')
a('      tried.push({ gen: c.gen, match: j.match, pub8: j.blt.slice(0, 11) });')
a('      if (j.match) { chosen = c; break; }')
a('    } catch (e) { tried.push({ gen: c.gen, err: String(e?.message ?? e).slice(0, 60) }); }')
a('  }')
a('  if (chosen) break;')
a('}')
a('if (!chosen) fail("NO-GEN-FITS-CHAIN", JSON.stringify(tried));')
a('console.log(chosen.wif);')

src = "\n".join(L) + "\n"
open(P, "w", encoding="utf-8").write(src)
back = open(P, encoding="utf-8").read()
if back != src:
    print("READBACK-MISMATCH"); sys.exit(1)
r = subprocess.run(["node", "--check", P], capture_output=True, text=True)
print("node --check rc=%s" % r.returncode)
if r.returncode != 0:
    print(r.stderr[:300]); sys.exit(1)
print("built bytes:", os.path.getsize(P))
